/** Desktop protocol/lifecycle verification; does not establish Android shader/NPU performance. */
import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1000, height: 700 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://127.0.0.1:4190/tests/realtime-sbs.html');
  await page.waitForFunction(() => document.querySelector('video')?.readyState >= 2);
  assert.equal(await page.locator('video').count(), 1);
  assert.equal(await page.locator('output').textContent(), 'off');
  await page.locator('#toggle').click();
  await page.waitForFunction(() => document.querySelector('output')?.textContent === 'frame');
  await page.waitForFunction(() => document.querySelector('canvas')?.getContext('2d').getImageData(0, 0, 1, 1).data[0] === 120);
  await page.evaluate(() => { window.sbsHarness.hold = true; });
  await page.waitForTimeout(100);
  const held = await page.evaluate(() => window.sbsHarness.frames.length);
  await page.waitForTimeout(2200);
  assert.equal(await page.locator('output').textContent(), 'stale');
  assert.equal(await page.locator('canvas').evaluate(x => x.getContext('2d').getImageData(0, 0, 1, 1).data[0]), 120, 'Delay must retain the previous depth preview');
  assert.equal(await page.evaluate(() => window.sbsHarness.frames.length), held, 'Only one frame may await acknowledgement');
  await page.locator('#toggle').click();
  const oldToken = await page.evaluate(() => window.sbsHarness.token);
  await page.waitForFunction(() => document.querySelector('output')?.textContent === 'off');
  await page.evaluate(token => window.dispatchEvent(new CustomEvent('tachi-depth', { detail: { token, status: 'frame', sequence: 1 } })), oldToken);
  assert.equal(await page.locator('output').textContent(), 'off', 'A late response must not reactivate conversion');
  await page.evaluate(() => { window.sbsHarness.hold = false; });
  await page.locator('#toggle').click();
  await page.waitForFunction(() => document.querySelector('output')?.textContent === 'frame');
  const beforeSeek = await page.evaluate(() => window.sbsHarness.token);
  await page.evaluate(() => document.querySelector('video').dispatchEvent(new Event('seeking')));
  await page.waitForFunction(token => window.sbsHarness.token !== token, beforeSeek);
  await page.locator('#subtitles').click();
  await page.waitForFunction(() => document.querySelector('output')?.textContent === 'subtitles');
  const stopped = await page.evaluate(() => window.sbsHarness.frames.length);
  await page.waitForTimeout(150);
  assert.equal(await page.evaluate(() => window.sbsHarness.frames.length), stopped);
  await page.locator('#subtitles').click();
  await page.waitForFunction(() => document.querySelector('output')?.textContent === 'frame');
  await page.evaluate(() => window.LucentNative.receiveBootstrapState({ source: 'android', displayMode: 'mirror_2d', displayModeApplied: true }));
  await page.waitForFunction(() => document.querySelector('output')?.textContent === 'needs-stereo');
  await page.evaluate(() => window.LucentNative.receiveBootstrapState({ source: 'android', displayMode: 'stereo_screen', displayModeApplied: true }));
  await page.waitForFunction(() => document.querySelector('output')?.textContent === 'frame');
  await page.evaluate(() => { window.sbsHarness.error = true; });
  await page.waitForFunction(() => document.querySelector('output')?.textContent === 'error');
  const starts = await page.evaluate(() => window.sbsHarness.starts.length);
  await page.evaluate(() => window.dispatchEvent(new Event('resize')));
  await page.waitForTimeout(150);
  assert.equal(await page.evaluate(() => window.sbsHarness.starts.length), starts, 'Failure must latch until explicit retry');
  await page.locator('#toggle').click();
  await page.evaluate(() => { window.sbsHarness.error = false; window.sbsHarness.hold = true; });
  await page.locator('#toggle').click();
  await page.waitForFunction(() => document.querySelector('output')?.textContent === 'stale');
  const heldStarts = await page.evaluate(() => window.sbsHarness.starts.length);
  const heldFrames = await page.evaluate(() => window.sbsHarness.frames.length);
  await page.waitForTimeout(250);
  assert.equal(await page.evaluate(() => window.sbsHarness.frames.length), heldFrames);
  await page.evaluate(() => {
    const frame = window.sbsHarness.frames.at(-1);
    window.sbsHarness.hold = false;
    window.dispatchEvent(new CustomEvent('tachi-depth', { detail: { ...frame, status: 'frame', nativeMs: 25 } }));
  });
  await page.waitForFunction(() => document.querySelector('output')?.textContent === 'frame');
  assert.equal(await page.evaluate(() => window.sbsHarness.starts.length), heldStarts, 'Late depth must resume without clearing/restarting the session');
  await page.evaluate(() => window.unmountSbs());
  assert.equal(await page.locator('video').count(), 0);
  assert.deepEqual(errors, []);
  console.log('PASS: single video, bounded frames, depth preview, stale response rejection, seek restart, subtitle gate, latched failure, teardown.');
} finally { await browser.close(); }
